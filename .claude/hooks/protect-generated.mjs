#!/usr/bin/env node
// PreToolUse(Edit|Write) guardrail.
// - HARD BLOCK edits to the generated registries / nav (they're rebuilt from nav-config + the .tsx modules).
// - SOFT WARN on edits to the design tokens / component CSS (the design system itself).
// Reads the hook payload as JSON on stdin; exit 2 = block (stderr shown to the agent).
let raw = '';
process.stdin.setEncoding('utf8');
process.stdin.on('data', (c) => (raw += c));
process.stdin.on('end', () => {
  let fp = '';
  try {
    const data = JSON.parse(raw || '{}');
    fp = data.tool_input?.file_path || data.tool_input?.path || '';
  } catch {
    /* no payload — allow */
  }
  const f = String(fp);

  if (
    f.endsWith('src/ds/migrated/registry.ts') ||
    f.endsWith('src/ds/examples/registry.ts') ||
    f.endsWith('src/lib/nav.ts')
  ) {
    process.stderr.write(
      'Blocked: ' +
        f.split('/').slice(-2).join('/') +
        ' is auto-generated. Edit src/ds/core/nav-config.js and/or add the .tsx module (src/ds/migrated/<ds>/<slug>.tsx, examples src/ds/examples/<name>.tsx), then regenerate with `node scripts/gen-nav.mjs && node scripts/gen-migrated.mjs` (+ `node scripts/gen-examples.mjs` for examples) instead.\n',
    );
    process.exit(2);
  }

  // Contract harness generated artifacts — never hand-edited.
  if (
    f.endsWith('FORGE-HEALTH.md') ||
    f.endsWith('reports/state.json') ||
    f.endsWith('tokens/forge.tokens.json')
  ) {
    process.stderr.write(
      'Blocked: ' + f.split('/').pop() +
        ' is generated by the contract harness. FORGE-HEALTH.md + reports/state.json come from `npm run forge:verify`; tokens/forge.tokens.json from `npm run gen:tokens`. To change the bar, edit packages/registry/forge.contract.json (clauses/waivers) or the token CSS, then regenerate.\n',
    );
    process.exit(2);
  }

  if (/src\/styles\/(tokens|ds)\.css$/.test(f)) {
    // Allow, but surface a reminder into the agent's context.
    console.log(
      JSON.stringify({
        hookSpecificOutput: {
          additionalContext:
            'Note: you are editing the design system source of truth (' +
            f.split('/').pop() +
            '). Prefer composing existing classes; only extend tokens/ds.css for a genuinely new building block, and keep dark/light + RTL parity.',
        },
      }),
    );
  }
  process.exit(0);
});
