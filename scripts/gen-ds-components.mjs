#!/usr/bin/env node
// Generate DS-COMPONENTS.md — the authoritative, grep-first index of every
// component/hook/type exported from @eidos/ui. Source of truth: the barrel
// packages/ui/src/index.ts + each re-exported module. Run: node scripts/gen-ds-components.mjs
import { readFileSync, existsSync, writeFileSync } from 'node:fs';
import { join, dirname } from 'node:path';

const ROOT = process.cwd();
const SRC = join(ROOT, 'packages/ui/src');
const barrel = readFileSync(join(SRC, 'index.ts'), 'utf8');

// modules re-exported by the barrel, in order
const modules = [...barrel.matchAll(/export \* from '\.\/([\w./-]+)'/g)].map((m) => m[1]);

const isComponent = (n) => /^[A-Z]/.test(n);
const rows = [];
for (const mod of modules) {
  const candidates = [`${mod}.tsx`, `${mod}.ts`, `${mod}/index.tsx`, `${mod}/index.ts`];
  const rel = candidates.find((c) => existsSync(join(SRC, c)));
  if (!rel) continue;
  const code = readFileSync(join(SRC, rel), 'utf8');
  const names = new Set();
  for (const m of code.matchAll(/export\s+(?:async\s+)?function\s+([A-Za-z_]\w*)/g)) names.add(m[1]);
  for (const m of code.matchAll(/export\s+const\s+([A-Za-z_]\w*)\s*[=:]/g)) names.add(m[1]);
  // export { A, B as C } — take the exported (outer) name
  for (const m of code.matchAll(/export\s+\{([^}]+)\}/g)) {
    for (const part of m[1].split(',')) {
      const name = part.trim().split(/\s+as\s+/).pop()?.trim();
      if (name && /^[A-Za-z_]\w*$/.test(name)) names.add(name);
    }
  }
  const comps = [...names].filter(isComponent).sort();
  if (comps.length) rows.push({ mod: rel, comps });
}

const total = rows.reduce((n, r) => n + r.comps.length, 0);
const out = [
  '# Eidos DS — component index',
  '',
  '> Generated by `node scripts/gen-ds-components.mjs` from `packages/ui/src/index.ts`. Do not edit by hand.',
  '',
  `**${total} components/exports across ${rows.length} modules.** Everything here is importable from \`@eidos/ui\` (or \`@/ds/core\`).`,
  '',
  'RULE: before building any UI, grep this file for what you need. If it exists, import it and read its props in the listed module — never hand-roll the markup/classes. If it does not exist, extend the DS (add it here), not the screen.',
  '',
  '| Module | Exports |',
  '| --- | --- |',
  ...rows.map((r) => `| \`packages/ui/src/${r.mod}\` | ${r.comps.map((c) => `\`${c}\``).join(' · ')} |`),
  '',
].join('\n');

writeFileSync(join(ROOT, 'DS-COMPONENTS.md'), out);
console.log(`wrote DS-COMPONENTS.md — ${total} exports across ${rows.length} modules`);
