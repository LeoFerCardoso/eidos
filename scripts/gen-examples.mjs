// Generates src/ds/examples/registry.ts — a typed loader map for the standalone
// IDP example screens (rendered full-screen at /example/<name>, outside the docs
// shell). Mirrors gen-migrated.mjs. Scans src/ds/examples/*.tsx, excluding the
// shared shell modules. Re-run after adding an example: `node scripts/gen-examples.mjs`.
import { readdirSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { dirname, resolve } from 'node:path';

const root = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const dir = resolve(root, 'src/ds/examples');

const EXCLUDE = new Set(['example-shell', 'ai-shell', 'registry']);

const names = readdirSync(dir)
  .filter((f) => f.endsWith('.tsx'))
  .map((f) => f.replace(/\.tsx$/, ''))
  .filter((n) => !EXCLUDE.has(n))
  .sort();

const entries = names.map((n) => `  ${JSON.stringify(n)}: () => import('./${n}'),`).join('\n');

const out = `// AUTO-GENERATED by scripts/gen-examples.mjs — do not edit by hand.
// Standalone IDP example screens (rendered at /example/<name>, no docs shell).
/* eslint-disable */
import type { ComponentType } from 'react';

export const EXAMPLES_REG: Record<string, () => Promise<{ default: ComponentType }>> = {
${entries}
};
`;

writeFileSync(resolve(dir, 'registry.ts'), out);
console.log(`Wrote src/ds/examples/registry.ts (${names.length} examples).`);
