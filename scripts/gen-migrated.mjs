// Generates src/ds/migrated/registry.ts — the loader map DSPageLoader resolves pages from.
// Scans src/ds/migrated/**/*.tsx RECURSIVELY; the key is the path relative to migrated/
// without the extension. Core pages stay flat (key `color`); sub-DS pages live in a
// subfolder (key `charts/area`, route /charts/area). Re-run after adding/moving a page:
// `node scripts/gen-migrated.mjs`.
import { readdirSync, writeFileSync, statSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { dirname, resolve, relative } from 'node:path';

const dir = resolve(dirname(fileURLToPath(import.meta.url)), '..', 'src/ds/migrated');

function walk(d) {
  const out = [];
  for (const name of readdirSync(d)) {
    const p = resolve(d, name);
    if (statSync(p).isDirectory()) out.push(...walk(p));
    else if (name.endsWith('.tsx')) out.push(p);
  }
  return out;
}

const keys = walk(dir)
  .map((p) => relative(dir, p).replace(/\.tsx$/, ''))
  .sort();

const entries = keys.map((k) => `  ${JSON.stringify(k)}: () => import('./${k}'),`).join('\n');

writeFileSync(
  resolve(dir, 'registry.ts'),
  `// AUTO-GENERATED by scripts/gen-migrated.mjs — do not edit by hand.
// Migrated idiomatic TSX pages, keyed by route (core flat; sub-DS namespaced as <ds>/<slug>).
// DSPageLoader renders these inside the persisted (ds) DocsShell.
/* eslint-disable */
import type { ComponentType } from 'react';

export const MIGRATED: Record<string, () => Promise<{ default: ComponentType }>> = {
${entries}
};
`,
);
console.log(`Wrote migrated registry with ${keys.length} pages.`);
